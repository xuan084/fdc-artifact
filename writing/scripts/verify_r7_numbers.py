def page_budget():
    section("Page budget (main.pdf: 12 pages, body ends on page 8, references begin on page 9)")
    pdf = IT / "writing/latex_acm/main.pdf"
    try:
        import pymupdf
    except ImportError:
        print("  [note] pymupdf not installed; page check skipped")
        return
    if not pdf.exists():
        print("  [note] main.pdf absent; page check skipped")
        return
    d = pymupdf.open(str(pdf))
    check("main.pdf pages", len(d), 12, 0)
    ref_page, ref_y, concl = None, None, None
    for i, p in enumerate(d):
        for b in p.get_text("blocks"):
            s = b[4].replace("\n", " ").strip()
            if s.startswith("REFERENCES") and ref_page is None:
                ref_page, ref_y = i + 1, b[1]
            if "by fixing its read plan first" in s or "read plan first." in s:
                concl = i + 1
    check("references begin on page 9", ref_page or 0, 9, 0)
    check("conclusion ends on page 8", concl or 0, 8, 0)
    p9 = d[8]
    body_on_9 = [b for b in p9.get_text("blocks") if 40 < b[0] < 570 and 75 < b[1] < (ref_y or 0) - 1
                 and not b[4].strip().isdigit()]
    check("no body text above the references heading on page 9", len(body_on_9), 0, 0)


