def check(label, computed, printed, tol):
    ok = abs(computed - printed) <= tol
    print(f"  [{'OK' if ok else 'MISMATCH'}] {label}: computed {computed:.6g}, paper {printed}")
    if not ok:
        FAIL.append(label)


def present(label, needle, where):
    txt = {"main": MAIN, "supp": SUPP}[where]
    ok = needle in txt
    print(f"  [{'OK' if ok else 'MISMATCH'}] {label}: {needle[:120]!r} printed in {where}")
    if not ok:
        FAIL.append(f"{label} (text)")


def absent(label, needle, where):
    txt = {"main": MAIN, "supp": SUPP}[where]
    ok = needle not in txt
    print(f"  [{'OK' if ok else 'MISMATCH'}] {label}: {needle[:120]!r} absent from {where}")
    if not ok:
        FAIL.append(f"{label} (stale text)")


def section(t):
    print(f"\n== {t}")


def J(p):
    return json.load(open(p))


def r6_chain(args):
    section("r6 chain (verify_r6 -> r5b -> r5 -> r4b -> r4 -> r3); only listed checks may fail")
    p = subprocess.run([sys.executable, str(HERE / "verify_r6_numbers.py"), *args], capture_output=True, text=True)
    out = p.stdout.splitlines()
    n_ok = sum("[OK]" in l for l in out)
    seen = set()
    for l in out:
        if "[MISMATCH]" not in l:
            continue
        key = l.strip().replace("[MISMATCH] ", "", 1)
        if key in SUPERSEDED:
            if key not in seen:
                print(f"  [SUPERSEDED] {key[:110]} -> {SUPERSEDED[key]}")
            seen.add(key)
        else:
            print(f"  [MISMATCH] r6 chain: {key}")
            FAIL.append(f"r6 chain: {key[:80]}")
    for k in SUPERSEDED:
        if k not in seen:
            print(f"  [note] superseded item not failing (string still present?): {k[:100]}")
    last = [l for l in out if l.startswith("r6:")]
    print(f"  chain: {n_ok} OK lines; {len(seen)} superseded checks; r6 final line: {last[-1][:40] if last else '(none)'}")
    if not last:
        FAIL.append("r6 chain produced no final line")
    if p.stderr.strip():
        print("  chain stderr:", p.stderr.strip()[-400:])
        FAIL.append("chain stderr")


